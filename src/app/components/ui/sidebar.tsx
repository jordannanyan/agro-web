/** Cookie key used to persist the desktop sidebar's open/closed state. */
const SIDEBAR_COOKIE_NAME = "sidebar_state";
/** Cookie lifetime: 7 days, in seconds. */
const SIDEBAR_COOKIE_MAX_AGE = 60 * 60 * 24 * 7;
/** Default sidebar width on desktop. */
const SIDEBAR_WIDTH = "16rem";
/** Sidebar width when rendered inside the mobile Sheet. */
const SIDEBAR_WIDTH_MOBILE = "18rem";
/** Sidebar width when collapsed to icon-only mode. */
const SIDEBAR_WIDTH_ICON = "3rem";
/** Keyboard shortcut (Cmd/Ctrl + key) used to toggle the sidebar. */
const SIDEBAR_KEYBOARD_SHORTCUT = "b";

/* -------------------------------------------------------------------------- */
/*                                   Context                                  */
/* -------------------------------------------------------------------------- */

type SidebarContextProps = {
  /** "expanded" | "collapsed" — mirrors `open` but as a CSS-friendly string. */
  state: "expanded" | "collapsed";
  /** Whether the desktop sidebar is open. */
  open: boolean;
  setOpen: (open: boolean) => void;
  /** Whether the mobile (Sheet-based) sidebar is open. */
  openMobile: boolean;
  setOpenMobile: (open: boolean) => void;
  isMobile: boolean;
  /** Toggles the sidebar, automatically targeting mobile or desktop state. */
  toggleSidebar: () => void;
};

const SidebarContext = React.createContext<SidebarContextProps | null>(null);

/**
 * Hook to access the current sidebar state.
 * Must be used within a `<SidebarProvider>`.
 */
function useSidebar() {
  const context = React.useContext(SidebarContext);
  if (!context) {
    throw new Error("useSidebar must be used within a SidebarProvider.");
  }

  return context;
}

/* -------------------------------------------------------------------------- */
/*                                  Provider                                  */
/* -------------------------------------------------------------------------- */

/**
 * Wraps the app (or layout) to provide sidebar state via context.
 * Handles mobile vs. desktop state, persistence via cookie, and the
 * Cmd/Ctrl+B keyboard shortcut.
 *
 * Supports both controlled (`open` / `onOpenChange`) and uncontrolled
 * (`defaultOpen`) usage.
 */
function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean;
  open?: boolean;
  onOpenChange?: (open: boolean) => void;
}) {
  const isMobile = useIsMobile();
  const [openMobile, setOpenMobile] = React.useState(false);

  // Internal (uncontrolled) state. When `open` is passed as a prop, the
  // component becomes controlled and this internal state is ignored.
  const [_open, _setOpen] = React.useState(defaultOpen);
  const open = openProp ?? _open;

  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value;
      if (setOpenProp) {
        setOpenProp(openState);
      } else {
        _setOpen(openState);
      }

      // Persist the desktop state so it survives page reloads.
      document.cookie = `${SIDEBAR_COOKIE_NAME}=${openState}; path=/; max-age=${SIDEBAR_COOKIE_MAX_AGE}`;
    },
    [setOpenProp, open],
  );

  /** Toggles mobile sheet or desktop sidebar, depending on viewport. */
  const toggleSidebar = React.useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open);
  }, [isMobile, setOpen, setOpenMobile]);

  // Global keyboard shortcut: Cmd/Ctrl + B toggles the sidebar.
  React.useEffect(() => {
    const handleKeyDown = (event: KeyboardEvent) => {
      if (
        event.key === SIDEBAR_KEYBOARD_SHORTCUT &&
        (event.metaKey || event.ctrlKey)
      ) {
        event.preventDefault();
        toggleSidebar();
      }
    };

    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [toggleSidebar]);

  // Derived string state, used for `data-state="expanded" | "collapsed"`
  // so consumers can style the sidebar purely with Tailwind data-attribute
  // selectors.
  const state = open ? "expanded" : "collapsed";

  const contextValue = React.useMemo<SidebarContextProps>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
    }),
    [state, open, setOpen, isMobile, openMobile, setOpenMobile, toggleSidebar],
  );

  return (
    <SidebarContext.Provider value={contextValue}>
      <TooltipProvider delayDuration={0}>
        <div
          data-slot="sidebar-wrapper"
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH,
              "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
              ...style,
            } as React.CSSProperties
          }
          className={cn(
            "group/sidebar-wrapper has-data-[variant=inset]:bg-sidebar flex min-h-svh w-full",
            className,
          )}
          {...props}
        >
          {children}
        </div>
      </TooltipProvider>
    </SidebarContext.Provider>
  );
}

